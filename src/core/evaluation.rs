use crate::core::model::{Position, Move, PieceType, Color};
use std::cmp::Ordering;

impl Position {
    pub fn value(&self) -> f32 {
        // All scores are calculated from white's perspective, and inverted if needed

        let mut material: f32 = 0.0;

        let mut material_score = 0.0;
        let mut development_score: f32 = 0.0;
        let mut endgame_score: f32 = 0.0;

        let mut current_king = false;
        let mut other_king = false;

        let mut white_bishops = 0;
        let mut black_bishops = 0;
        let mut white_rooks = 0;
        let mut black_rooks = 0;

        for row in 0..8 {
            for column in 0..8 {
                if let Some(piece) = self.board[row][column] {
                    let s = piece.t.value();
                    material_score += if piece.color == Color::White { s } else { -s };
                    material += s;

                    if piece.color == Color::White {
                        development_score += BONUS_TABLES[piece.t as usize][0][row][column];
                        endgame_score += BONUS_TABLES[piece.t as usize][1][row][column];
                    } else {
                        development_score -= BONUS_TABLES[piece.t as usize][0][7 - row][column];
                        endgame_score -= BONUS_TABLES[piece.t as usize][1][7 - row][column];
                    }

                    if piece.t == PieceType::Bishop {
                        if piece.color == Color::White {
                            white_bishops += 1;
                        } else {
                            black_bishops += 1;
                        }
                    } else if piece.t == PieceType::Rook {
                        if piece.color == Color::White {
                            white_rooks += 1;
                        } else {
                            black_rooks += 1;
                        }
                    } else if piece.t == PieceType::King {
                        if piece.color == self.current_player {
                            current_king = true;
                        } else {
                            other_king = true;
                        }
                    }

                }
            }
        }

        if !current_king {
            return -1.0;
        }

        if !other_king {
            return 1.0;
        }

        let phase = material / 78.0;
        let mut score = material_score + development_score * phase + endgame_score * (1.0 - phase);

        if white_bishops == 2 {
            score += 0.5;
        }

        if black_bishops == 2 {
            score -= 0.5;
        }

        if white_rooks == 2 {
            score -= 0.3;
        }

        if black_rooks == 2 {
            score += 0.3;
        }

        if self.current_player == Color::Black {
            score = -score;
        }

        // We divide by 100 to ensure that checkmate (whose absolute value is 1)
        // is always preferred when possible
        score / 100.0
    }
}

impl PartialOrd for Move {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        if self.promotion != other.promotion {
            return Some(other.promotion.cmp(&self.promotion));
        }

        if self.captured != other.captured {
            return Some(other.captured.cmp(&self.captured));
        }

        None
    }
}

impl PieceType {
    pub fn value(&self) -> f32 {
        match self {
            PieceType::Pawn => 1.0,
            PieceType::Knight => 3.0,
            PieceType::Bishop => 3.0,
            PieceType::Rook => 5.0,
            PieceType::Queen => 9.0,
            PieceType::King => 0.0
        }
    }
}


